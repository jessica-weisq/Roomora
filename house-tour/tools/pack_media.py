"""Bundle every image property.js uses into js/media-data.js, so 3D views work when index.html
is opened straight from disk (browsers block 3D textures from local files otherwise).
Run after adding or changing photos: python3 tools/pack_media.py"""
import base64, json, mimetypes, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "property.js").read_text()
prop = json.loads(src[src.index("=") + 1:].strip().rstrip(";"))
paths = set()
for r in prop["rooms"]:
    for m in r["media"]:
        paths.update(p for p in (m.get("src"), m.get("depth")) if p)
        for pt in (m.get("fused") or {}).get("parts", []):
            paths.update(p for p in (pt.get("src"), pt.get("depth")) if p)
for f in prop.get("furnishing", []):
    if f.get("src"):
        paths.add(f["src"])
out = {}
for p in sorted(paths):
    f = root / p
    if f.exists():
        out[p] = "data:" + (mimetypes.guess_type(str(f))[0] or "image/jpeg") + ";base64," + base64.b64encode(f.read_bytes()).decode()
(root / "js" / "media-data.js").write_text("// Generated by tools/pack_media.py. Don't edit by hand.\nwindow.TOUR_MEDIA = " + json.dumps(out) + ";\n")
print(f"packed {len(out)} images into js/media-data.js")
